/// ประเภทหลักฐานที่นิสิตเลือกตอนอัปโหลด (backend: `EvidenceKind`)
///
/// * `certificate` — เกียรติบัตร/ใบรับรอง → OCR อนุมัติอัตโนมัติได้ตามเกณฑ์
/// * `photo` / `other` — ภาพถ่ายกิจกรรม / อื่น ๆ → เจ้าหน้าที่ตรวจเสมอ
///
/// OCR ยืนยันได้แค่ว่า "งานจัดจริง" จากข้อความบนใบ ยืนยันตัวตนคนในภาพถ่ายหน้าแบนเนอร์ไม่ได้
library;

/// ลำดับตัวเลือกในฟอร์มอัปโหลด
const kEvidenceKinds = ['certificate', 'photo', 'other'];

/// ข้อความช่วยใต้ตัวเลือก — บอกล่วงหน้าว่าภาพถ่ายจะไม่ถูกอนุมัติทันที
const kEvidenceKindUploadHint = 'ภาพถ่ายจะถูกส่งให้เจ้าหน้าที่ตรวจ ไม่อนุมัติอัตโนมัติ';

/// หัวข้อตัวเลือกในฟอร์มอัปโหลด
String evidenceKindOptionLabel(String kind) => switch (kind) {
      'certificate' => 'เกียรติบัตร / ใบรับรอง',
      'photo' => 'ภาพถ่ายกิจกรรม (หน้าแบนเนอร์/สถานที่)',
      _ => 'อื่น ๆ',
    };

/// คำอธิบายสั้นใต้หัวข้อตัวเลือก
String evidenceKindOptionDetail(String kind) => switch (kind) {
      'certificate' => 'มีชื่อของนิสิตบนใบ — ระบบตรวจอัตโนมัติได้',
      'photo' => 'ภาพตัวเองในงาน — เจ้าหน้าที่ตรวจด้วยตา',
      _ => 'หลักฐานแบบอื่น — เจ้าหน้าที่ตรวจด้วยตา',
    };

/// ใบประเภทนี้ต้องให้คนตรวจเสมอไหม — null (ไฟล์ก่อนมีประเภท) ถือเป็นเกียรติบัตร
bool evidenceKindNeedsHumanReview(String? kind) => kind == 'photo' || kind == 'other';

/// ป้ายในหน้าตรวจ OCR — บอกเจ้าหน้าที่ว่าทำไมใบนี้ไม่ถูกอนุมัติอัตโนมัติ
String evidenceKindReviewLabel(String? kind) => switch (kind) {
      'photo' => '📷 ภาพถ่ายกิจกรรม — ต้องตรวจด้วยตา',
      'other' => '📎 หลักฐานอื่น ๆ — ต้องตรวจด้วยตา',
      _ => '📄 เกียรติบัตร / ใบรับรอง',
    };

/// ป้ายสั้นสำหรับตาราง/แถวแคบ (คิวตรวจ · รายชื่อผู้เข้าร่วม) — ข้อความเต็มกินที่จนปุ่มหลุดขอบ
String evidenceKindShortLabel(String? kind) => switch (kind) {
      'photo' => '📷 ภาพถ่าย · ตรวจด้วยตา',
      'other' => '📎 อื่น ๆ · ตรวจด้วยตา',
      _ => '📄 เกียรติบัตร',
    };
